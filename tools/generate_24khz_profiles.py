"""Generate the firmware's named register writes from the recorded bench profiles."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
def generate():
    profiles = [json.loads((ROOT / 'bench-configs' / name).read_text())['fields'] for name in
        ('outrun-ms9-384p-candidate.json', 'outrun-toei-426-candidate.json')]
    lines = ['// Generated by tools/generate_24khz_profiles.py; edit the source profiles.',
             '#pragma once', 'inline void writeOutrun24kProfile(bool toei) {']
    for name, value in profiles[0].items():
        other = profiles[1][name]
        expression = str(value) if value == other else f'(toei ? {other} : {value})'
        lines.append(f'    GBS::{name}::write({expression});')
    lines += ['}', 'inline void writeStandardRgbhv24kProfile() {']
    standard = json.loads((ROOT / 'bench-configs/standard-rgbhv-384p-candidate.json').read_text())['fields']
    lines += [f'    GBS::{name}::write({value});' for name, value in standard.items()]
    lines += ['}', 'inline void writeToei43Profile() {']
    toei = json.loads((ROOT / 'bench-configs/vt3-toei-52hz-candidate.json').read_text())['fields']
    lines += [f'    GBS::{name}::write({value});' for name, value in toei.items()]
    lines += ['}', '']
    return '\n'.join(lines)
if __name__ == '__main__':
    (ROOT / 'profiles_24khz.h').write_text(generate())

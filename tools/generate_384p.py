"""Generate the experimental 384-line preset from the NTSC downscaler."""
from pathlib import Path
import re
ROOT = Path(__file__).resolve().parents[1]
FW = ROOT
PATTERN = re.compile(r'(0x[0-9a-fA-F]+),\s*//\s*s(\d)_([0-9a-fA-F]+)')

def generate():
    source = (FW / 'ntsc_downscale.h').read_text()
    registers = {(int(s), int(a, 16)): int(v, 16) for v, s, a in PATTERN.findall(source)}
    def field(segment, address, offset, width, value):
        assert 0 <= value < (1 << width)
        for bit in range(width):
            key = segment, address + (offset + bit) // 8
            mask = 1 << ((offset + bit) % 8)
            registers[key] = (registers[key] & ~mask) | (((value >> bit) & 1) * mask)
    # Bench frame periods fit inclusive counters: 2641 clocks x 411 lines.
    # Nominal 64.8 MHz gives 24.536 kHz / 59.698 Hz (connector measurement pending).
    field(0, 0x41, 0, 8, 0x55)
    field(1, 0x2b, 0, 7, 7)
    field(3, 0x01, 0, 12, 2640)
    field(3, 0x02, 4, 11, 410)
    # Preserve the horizontal proportions of the source preset (2558 clocks).
    for addr, offset, value in [(4, 0, 2354), (5, 4, 324), (10, 0, 160),
                                 (11, 4, 8), (16, 0, 2418), (17, 4, 440)]:
        field(3, addr, offset, 12, round(value * 2640 / 2558))
    field(3, 0x16, 0, 10, round(512 * 2558 / 2640))
    # Segment2 is loaded separately; runtime applies fractional 480-to-384 rates.
    field(3, 0x00, 5, 1, 1)  # fractional stage already produces 384 lines
    field(3, 0x17, 4, 10, 1023)
    field(3, 0x07, 0, 11, 18)
    field(3, 0x08, 4, 11, 20)
    field(3, 0x0d, 0, 11, 5)  # retain negative sync polarity
    field(3, 0x0e, 4, 11, 1)
    field(3, 0x13, 0, 11, 408)
    field(3, 0x14, 4, 11, 24)  # 408 - 24 = 384 active lines
    field(3, 0x20, 0, 11, 412)
    field(3, 0x22, 0, 11, 412)
    # External blanking must describe this raster, not the inherited 240p one.
    field(3, 0x6d, 0, 12, registers[3, 0x10] | ((registers[3, 0x11] & 15) << 8))
    field(3, 0x6e, 4, 12, (registers[3, 0x11] >> 4) | (registers[3, 0x12] << 4))
    field(3, 0x70, 0, 11, 408)
    field(3, 0x71, 4, 11, 24)
    result = PATTERN.sub(lambda m: f'0x{registers[int(m[2]), int(m[3], 16)]:02X}, // s{m[2]}_{m[3]}', source)
    return ('// EXPERIMENTAL: generated by tools/generate_384p.py; bench validation required.\n'
            '// Nominal 64.8 MHz / 2641 / 411 = 24.536 kHz / 59.698 Hz; 384 active lines.\n'
            + result.replace('ntsc_downscale[]', 'ntsc_384p[]'))

if __name__ == '__main__':
    (FW / 'ntsc_384p.h').write_text(generate())
